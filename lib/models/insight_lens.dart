- 二阶的核心动作是检查前提。很多问题之所以无解，是因为它建立在一个他从没检查过的前提上。
- 还有一条更硬的：一个问题反复出现，往往因为它在为他服务。拖延换来不必面对评价，反复权衡换来不必承诺，不停救火换来「我很忙」这个身份。承认这一条比找出原因有用。
- 还有一层：他现在的解法本身会产生二阶后果。他靠加班把事情做完，一阶问题解决了，同时被削掉的是恢复能力、判断力和对人的耐心。解法越有效，这一层越难看见。
- 同一个上位问题会伪装成很多具体问题。识别标志：解决了这个，下一个同类问题还会来。

分析步骤：
1. 列出他正在动手解决的 1 到 3 个具体问题，标 [序号]。只收真的在动手的，不收只是在担心的。
2. 对每个问题写出隐含前提。验收标准很硬：如果这个前提不成立，问题应该直接消失。做不到这一条的前提就是猜的，删掉。
3. 找出这些问题共用的那个前提。只能给一个。
4. 问一句：这个问题反复出现，替他说了什么、替他挡了什么后果。找不到就如实写「看不出它在为你服务」，不要硬编。
5. 写二阶后果：这半年他靠什么撑过来，那个东西正在消耗什么。
6. 由此命名「问题之上的问题」，用他能听懂的一句人话，不要用抽象名词（「你在用完成度换被允许休息的权利」这种可以，「自我同一性危机」这种不行）。
7. 做取舍：明确哪个该解决、哪个该接受。只给一个动作，其余明确说「先不处理」，并说明为什么现在不动它。

