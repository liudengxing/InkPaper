这个视角的内核：
- 霍华德·马克斯的原意：一阶思维说「这是家好公司，买进」；二阶思维说「所有人都觉得它是好公司，所以价格里已经包含了这个判断，该卖」。差别不在于多想一步，而在于把「共识是什么、我的判断和共识差在哪」也算进去。
